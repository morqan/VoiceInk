//
//  SelfCorrectionLexicon.swift
//  VoiceInk
//
//  Маркеры САМОИСПРАВЛЕНИЙ — сигналы, что говорящий правит только что сказанное
//  («вернее», «я хотел сказать», «или нет», «нет, не так»…). По ним считается
//  метрика «Гладкость»: чем больше ремонтов на 100 слов, тем меньше гладкость.
//
//  Намеренно НЕ пересекается с пулом паразитов (FillerLexicon): здесь только
//  то, что указывает на ПЕРЕДЕЛКУ фразы, а не общий хедж/дискурсивный маркер.
//  «точнее», «то есть», «в общем» оставлены паразитам — как одиночные слова они
//  чаще заполнитель, чем ремонт.
//
//  Многословные матчатся через PhraseOccurrenceScanner (границы слов, длинные
//  фразы первыми, без двойного счёта вложений).
//

import Foundation

enum SelfCorrectionLexicon {

    /// Ремонт-маркеры. Lowercase, регистронезависимый матч.
    /// Длинные варианты раньше коротких неважно — это делает сканер сам.
    static let markers: [String] = [
        // прямая правка слова
        "вернее", "поправлюсь", "поправка", "оговорился", "оговорилась",
        "я хотел сказать", "что я хотел сказать", "хотел сказать",
        "я имею в виду", "имею в виду", "в смысле",
        // отмена сказанного и перезаход
        "или нет", "хотя нет", "хотя не так", "нет не то", "нет не так",
        "нет погоди", "нет подожди", "нет стоп", "нет стой", "стоп не так",
        // оценка собственной формулировки
        "не то слово", "не то чтобы", "не так выразился",
        "неправильно сказал", "неверно сказал",
        "лучше сказать", "лучше так сказать", "как бы лучше сказать",
        "если точнее", "точнее говоря", "вернее говоря"
    ]

    /// Слова, у которых удвоение подряд — это ЭМФАЗА/разговорная норма, а не запинка.
    /// «так-так», «ну-ну», «да-да», «чуть-чуть» — не считаем за рестарт.
    static let reduplicationAllowed: Set<String> = [
        "так", "ну", "да", "нет", "ой", "эх", "хе", "ха", "но", "вот",
        "уже", "чуть", "еле", "тихо", "тише", "давай", "хорошо", "ладно",
        "тук", "кап", "бам", "топ"
    ]
}
